"""Generate ``verifier_card.md`` from the download manifest.

    python -m rafr.verifiers.cards.generate \\
        --manifest /workspace/models/model_manifest.json \\
        --out-dir src/rafr/verifiers/cards

The design requires the card to state: model identity, HF repo + commit hash + weight sha256,
how tau_i is determined, score direction and range, the batch cap, and the determinism
guarantee. the authors additionally asked for the truncation policy, which logit / which class the
score is read from, and the normalisation. Every one of those has a section below.

The revision and the sha256 are never typed in: they come from the manifest
the RunPod driver (not released) writes when it downloads the weights. A model that is not in the
manifest gets a card that says so, rather than a card with a blank where the hash should be.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from rafr.verifiers.candidates import registry
from rafr.verifiers.candidates.base import UNPINNED, VerifierConfigError
from rafr.verifiers.candidates.registry import CandidateSpec

DEFAULT_OUT_DIR = Path(__file__).resolve().parent
TAU_POINTER = "frozen/tau.json"
PENDING = "PENDING"


def _manifest_entry(manifest: dict[str, Any], repo_id: str) -> dict[str, Any]:
    return dict((manifest.get("models") or {}).get(repo_id) or {})


def _weights_table(entry: dict[str, Any]) -> list[str]:
    files = entry.get("weight_files") or []
    if not files:
        return [f"  _{PENDING}: this model is not in the download manifest._"]
    lines = ["| file | bytes | sha256 |", "|---|---|---|"]
    for f in files:
        lines.append(
            f"| `{f.get('path', '?')}` | {f.get('bytes', '?')} | `{f.get('sha256', '?')}` |"
        )
    return lines


def _describe(spec: CandidateSpec) -> tuple[Any, str | None]:
    """Build the candidate so its own strings can be copied into the card.

    Returns ``(verifier, blocked_reason)``: a candidate whose pending decision is still
    unanswered cannot be built, and the card then says which decision is missing instead of
    inventing a normalisation.
    """
    try:
        return registry.build(spec.name), None
    except VerifierConfigError as exc:
        return None, str(exc)


def render_card(spec: CandidateSpec, manifest: dict[str, Any]) -> str:
    entry = _manifest_entry(manifest, spec.repo_id)
    revision = str(entry.get("revision") or "").strip() or UNPINNED
    verifier, blocked = _describe(spec)

    truncation = registry.truncation()
    batch_limit: Any = PENDING
    semantics: Any = f"{PENDING} - {blocked}"
    normalization: Any = f"{PENDING} - {blocked}"
    verifier_id: Any = spec.name
    if verifier is not None:
        batch_limit = verifier.batch_limit
        semantics = verifier.score_semantics
        normalization = verifier.normalization
        verifier_id = verifier.verifier_id
        truncation = verifier.truncation

    out: list[str] = []
    add = out.append
    add(f"# verifier_card: {spec.name}")
    add("")
    add("Generated by `python -m rafr.verifiers.cards.generate`. Do not edit by hand:")
    add("the revision and the hashes come from the download manifest, everything else from")
    add("`rafr.verifiers.candidates`. Protocol App. A.2.")
    add("")

    add("## Model identity")
    add("")
    add("| field | value |")
    add("|---|---|")
    add(f"| candidate | `{spec.name}` |")
    add(f"| verifier_id | `{verifier_id}` |")
    add(f"| HF repo | `{spec.repo_id}` |")
    add(f"| commit revision | `{revision}` |")
    add(f"| model_version (scores table) | `{spec.repo_id}@{revision}` |")
    add(f"| family | {spec.kind} |")
    add(f"| license | {spec.license} |")
    add(f"| gated on the Hub | {'yes (manual approval + HF_TOKEN)' if spec.gated else 'no'} |")
    add(f"| weights dtype | {spec.dtype} |")
    add(f"| repo name checked against the Hub API on | {registry.VERIFIED_ON} |")
    add("")
    if spec.notes:
        add(spec.notes)
        add("")

    add("## Weight files (sha256)")
    add("")
    out.extend(_weights_table(entry))
    add("")
    if entry.get("downloaded_at"):
        add(f"Downloaded at {entry['downloaded_at']}.")
        add("")

    add("## Score")
    add("")
    add("| field | value |")
    add("|---|---|")
    add("| range | [0, 1] |")
    add("| direction | higher = more toxic |")
    add(f"| read from | {semantics} |")
    add(f"| normalisation | {normalization} |")
    add(f"| batch cap per `score()` call | {batch_limit} |")
    add("")
    add("Scales are not comparable between V1 and V2 and nothing downstream subtracts one")
    add("from the other (II.7.1, C.4).")
    add("")

    add("## Truncation")
    add("")
    add(f"{truncation.describe()}.")
    add("")
    if spec.kind == registry.GUARD_LM:
        add("The *text* is truncated before it is placed in the prompt, so the policy and the")
        add("instructions around it are never cut.")
        add("")

    add("## tau_i")
    add("")
    add("Not applied here. `score()` returns a raw score; tau_i is fitted on D_fit by")
    add(f"`rafr.validity.tau` (F1-max, plateau midpoint, II.4.1) and frozen in `{TAU_POINTER}`.")
    add("The judgment y_i = 1[s_i >= tau_i] and the margin m_i = s_i - tau_i are computed by")
    add("`rafr.formatter.fields`, never inside the verifier.")
    add("")

    add("## Determinism")
    add("")
    add("Same `(model_version, text)` gives the same score bit-for-bit, across calls and")
    add("across processes:")
    add("")
    add("* `model.eval()` under `torch.inference_mode()`: no dropout, no autograd;")
    add("* one forward pass, logits only. Nothing is generated and nothing is sampled;")
    add("* eager attention, so no runtime-chosen SDPA / flash reduction order;")
    add("* TF32 off, cuDNN autotuning off, `torch.use_deterministic_algorithms(True)`,")
    add("  `CUBLAS_WORKSPACE_CONFIG=:4096:8`;")
    add("* fixed padded sequence length and fixed batch shape, so the reduction order cannot")
    add("  depend on the neighbouring texts or on how full the last batch was. The inference")
    add("  batch size is therefore an engineering knob that cannot move a score.")
    add("")
    if blocked:
        add("## Pending decision")
        add("")
        add(f"This candidate cannot be built yet: {blocked}")
        add("")
    return "\n".join(out).rstrip() + "\n"


def write_cards(
    manifest: dict[str, Any], out_dir: Path, only: Sequence[str] | None = None
) -> list[Path]:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    wanted = list(only) if only else registry.names()
    written: list[Path] = []
    for name in wanted:
        spec = registry.spec(name)
        path = out_dir / f"{name}.md"
        path.write_text(render_card(spec, manifest), encoding="utf-8", newline="\n")
        written.append(path)
    return written


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument(
        "--manifest",
        type=Path,
        help=f"JSON from env/download_models.sh (default: ${registry.MANIFEST_ENV} or "
        f"{registry.DEFAULT_MANIFEST})",
    )
    p.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    p.add_argument(
        "--only", nargs="*", help=f"candidate names; default all ({len(registry.CANDIDATES)})"
    )
    return p


def main(argv: Sequence[str] | None = None, echo: Any = None) -> int:
    args = build_parser().parse_args(argv)
    say = echo or print
    path = args.manifest or registry.manifest_path()
    manifest = registry.load_manifest(path)
    if not manifest:
        say(f"no download manifest at {path}: cards will say the weights are not pinned")
    for written in write_cards(manifest, args.out_dir, args.only):
        say(f"wrote {written}")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
